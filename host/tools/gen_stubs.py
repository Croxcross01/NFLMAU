"""Generate stubs_gen.cpp: a logging stub for every imported system function the host does not implement yet.
usage: gen_stubs.py <generated ppc dir> <host src dir> <out.cpp>"""
import re, sys, pathlib
ppc, src, out = map(pathlib.Path, sys.argv[1:4])
imports = sorted(set(re.findall(r'__imp__([A-Za-z0-9_]+)', (ppc / 'ppc_recomp_shared.h').read_text())))
implemented = set()
for f in src.glob('*.cpp'):
    if f.name == out.name: continue
    t = f.read_text()
    implemented |= set(re.findall(r'\bIMP\(([A-Za-z0-9_]+)\)', t))
    implemented |= set(re.findall(r'PPC_FUNC\(__imp__([A-Za-z0-9_]+)\)', t))
missing = [n for n in imports if n not in implemented]
with open(out, 'w') as f:
    f.write('// generated by tools/gen_stubs.py: logging stubs for imports the host does not implement yet\n#include "host.h"\n')
    for n in missing: f.write(f'PPC_FUNC(__imp__{n}) {{ HostUnimplemented("__imp__{n}", ctx); }}\n')
print(f'{len(imports)} imports, {len(imports) - len(missing)} implemented, {len(missing)} stubbed')
